import { z } from "zod";
import { registerTool } from "../tool-registry.js";
import { buildSeoTemplate } from "../seo/templates.js";

const templateSchema = z.object({
  kind: z.enum(["landing", "blog", "app", "hybrid"]).optional(),
  siteUrl: z.string().max(500).optional(),
  pagePath: z.string().max(500).optional(),
  title: z.string().max(200).optional(),
  description: z.string().max(500).optional(),
  lang: z.string().max(20).optional(),
  imageUrl: z.string().max(1000).optional(),
});

/**
 * Шаблон — не замена реальному контенту. Он даёт агенту точный каркас head, JSON-LD,
 * 404.html и _redirects, чтобы SEO не оставалось «сделаем позже». Sitemap/robots намеренно
 * не создаются: их генерирует хостинг из реальных HTML релиза.
 */
registerTool({
  name: "seo.templates",
  description:
    "Return ready-to-use SEO fragments for a page: title/description/canonical/Open Graph/Twitter, " +
    "JSON-LD, public/404.html and a commented public/_redirects template. Input: " +
    "{kind?:'landing'|'blog'|'app'|'hybrid', siteUrl?:string, pagePath?:string, title?:string, " +
    "description?:string, lang?:string, imageUrl?:string}. Use it before implementing a public " +
    "landing/blog page or a hybrid site, then adapt the snippets to the project's framework and write " +
    "them with fs.write. It does not publish and does not create sitemap/robots: those are generated by " +
    "the hosting overlay from the release, so do not add duplicate sitemap.xml/robots.txt unless the " +
    "user explicitly needs custom files. For content sites prefer static HTML/SSG, not a React SPA; " +
    "for a SaaS use hybrid with public pages separate from /app/*.",
  parameters: {
    type: "object",
    additionalProperties: false,
    properties: {
      kind: { type: "string", enum: ["landing", "blog", "app", "hybrid"] },
      siteUrl: { type: "string", description: "Публичный origin проекта, например https://example.ru" },
      pagePath: { type: "string", description: "Путь страницы; по умолчанию /" },
      title: { type: "string" },
      description: { type: "string" },
      lang: { type: "string", description: "Язык страницы, по умолчанию ru" },
      imageUrl: { type: "string", description: "Абсолютный URL изображения для Open Graph" },
    },
  },
  execute: async input => {
    const value = templateSchema.parse(input ?? {});
    return buildSeoTemplate(value);
  },
});
