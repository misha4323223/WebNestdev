export type PlanId = keyof typeof PLAN_CATALOG;
/** Тариф аккаунта без подписки. Действующий тариф читается из оплаченной подписки (billing/store.ts). */
export const FREE_PLAN: PlanId = "free";
export type UsageKind = "agentRuns" | "browserChecks" | "webSearches";
export type UsageSnapshot = { date: string; agentRuns: number; browserChecks: number; webSearches: number };
export function limitsForPlan(plan: PlanId) { return PLAN_CATALOG[plan].limits; }

/** Месячный бюджет кредитов; 0 — кредитов нет, действует дневной лимит запусков. */
export function creditPoolFor(plan: PlanId): number {
  return PLAN_CATALOG[plan].limits.agentCreditsPerMonth;
}

/**
 * Сырой токенный пул остался только для админской аналитики и старых надбавок. Пользовательский
 * лимит платного тарифа — `agentCreditsPerMonth`.
 */
export function tokenPoolFor(plan: PlanId): number {
  return PLAN_CATALOG[plan].limits.agentTokensPerMonth;
}

export type IntegrationKind = "cloud" | "domains" | "services";
/** Сколько подключений данного вида разрешено тарифом; `null` — без ограничения. */
export function integrationLimitFor(plan: PlanId, kind: IntegrationKind): number | null {
  return PLAN_CATALOG[plan].limits.integrations[kind];
}

/** Сколько пользовательских доменов разрешено тарифом; 0 — функция недоступна. */
export function customDomainLimitFor(plan: PlanId): number {
  return PLAN_CATALOG[plan].limits.customDomains;
}

/**
 * Предел размера репозитория при импорте. Бесплатный тариф принимает проекты до 50 МБ:
 * импорт скачивает каждый файл и сразу пишет его в рабочую область, поэтому большой
 * репозиторий — это ещё и долгая загрузка на общей машине. На платных тарифах предела нет.
 */
export const FREE_REPOSITORY_IMPORT_BYTES = 50 * 1024 * 1024;
export function repositoryImportLimitFor(plan: PlanId): number | null {
  return plan === FREE_PLAN ? FREE_REPOSITORY_IMPORT_BYTES : null;
}

/**
 * Отправка коммитов обратно в чужой репозиторий — возможность платных тарифов. На бесплатном
 * тарифе проект можно импортировать и вести локальную историю, но не менять удалённую ветку.
 */
export function repositoryPushAllowedFor(plan: PlanId): boolean {
  return plan !== FREE_PLAN;
}

export const FREE_REPOSITORY_PUSH_MESSAGE = "На бесплатном тарифе отправка коммитов в репозиторий недоступна. Оформите платный тариф, чтобы пушить изменения обратно в GitHub, GitLab, GitVerse или SourceCraft.";

/** Сообщение для панели: размеры в мегабайтах, а не в байтах. */
export function repositorySizeLabel(bytes: number) {
  return Math.max(1, Math.round(bytes / (1024 * 1024))) + " МБ";
}

/**
 * Подписка и баланс аккаунта — то, что видит вкладка биллинга.
 *
 * `status: "canceled"` — подписка ещё действует до `renewsAt`, но автопродление выключено.
 * `paymentConnected` говорит, настроен ли приём денег; без него кнопки оплаты не показываются.
 */
export type BillingSubscription = {
  plan: PlanId;
  planName: string;
  priceLabel: string;
  status: "active" | "canceled";
  startedAt: string;
  renewsAt: string | null;
  paymentConnected: boolean;
  autoRenew: boolean;
  amountRub: number;
  /** Услуга периодических платежей включена в магазине: только тогда можно обещать автопродление. */
  recurringAvailable: boolean;
};

export type BillingBalance = { amount: number; currency: string; paymentsConnected: boolean };

/** Подписка бесплатного тарифа: у неё нет срока и автопродления. */
export function subscriptionFor(plan: PlanId, startedAt: string, extra: Partial<BillingSubscription> = {}): BillingSubscription {
  return {
    plan,
    planName: PLAN_CATALOG[plan].name,
    priceLabel: PLAN_CATALOG[plan].priceLabel,
    status: "active",
    startedAt,
    renewsAt: null,
    paymentConnected: false,
    autoRenew: false,
    amountRub: PLAN_CATALOG[plan].priceRub,
    recurringAvailable: false,
    ...extra,
  };
}

/** Баланс — сумма на счёте аккаунта. Пока оплата не подключена, на счёте ничего нет. */
export function balanceFor(): BillingBalance {
  return { amount: 0, currency: "RUB", paymentsConnected: false };
}

/**
 * Отображение тарифа: цена приходит с сервера, поэтому интерфейс не хранит суммы у себя.
 * Действующий тариф аккаунта — `accountPlanFor` в billing/store.ts: он читает оплаченную подписку.
 */
export function planView(plan: PlanId) {
  return { ...PLAN_CATALOG[plan], priceRub: PLAN_CATALOG[plan].priceRub };
}
