/** Длинная сторона уменьшенной копии. 1800 px хватает, чтобы разглядеть интерфейс. */
export const CONTEXT_IMAGE_MAX_EDGE = 1800;

/** Качество WebP для контекста: заметно меньше PNG, текст и границы остаются читаемыми. */
