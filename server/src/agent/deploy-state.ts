import type { DeployPlan } from "../deploy/deploy-plan.js";

/**
 * Нужны ли инструменты развёртывания — по состоянию проекта, а не только по словам в реплике.
 *
 * `deploy_project.md` — закладка развёртывания: она переживает перезагрузку, новый чат и обрезку
 * контекста. Если в ней есть незавершённые шаги, «продолжай» — это продолжение деплоя, даже когда
 * в самой реплике нет ни одного слова про деплой. Раньше такой запуск оставался без
 * `deploy.status`, хотя промт требовал звать его первым.
 *
 * Завершённый план инструментов не добавляет: это история, а не текущая работа. Пустой файл без
 * шагов тоже не считается работой в процессе — его ещё нужно написать через `deploy.plan`.
 */
export function hasActiveDeployPlan(
  plan: Pick<DeployPlan, "exists" | "complete" | "total"> | null | undefined,
): boolean {
  if (!plan?.exists) return false;
  return plan.total > 0 && plan.complete !== true;
}
