/**
 * Короткая реплика не значит мелкая задача.
 *
 * Автоматическая глубина рассуждения смотрела только на длину текста и ключевые слова вроде
 * «архитектура» или «миграция». «Сделай интернет-магазин с корзиной» — 31 символ и ни одного
 * такого слова, поэтому весь запуск шёл на `low`. Здесь отдельный, узкий признак: глагол сборки
 * плюс название продукта. Это не оценка сложности, а повод не начинать большую сборку с самой
 * дешёвой глубины.
 */
const BUILD_VERB_RE = /(сделай|создай|сверстай|разработай|напиши|построй|собери|нужен|нужно|нужна|требуется|build|make|create|write|need)/i;
const PRODUCT_RE = /(магазин|корзин|каталог|маркетплейс|личный кабинет|кабинет|авториз|регистрац|оплат|подписк|дашборд|админк|бронирован|расписан|доставк|заказ|crm|saas|лендинг|портфолио|блог|форум)/i;

/** До 240 символов: длинную реплику и так ловит общий признак сложной задачи. */
const MAX_CHARS = 240;

export function looksLikeProductBuild(task: string): boolean {
  const value = task.trim();
  return value.length > 0 && value.length <= MAX_CHARS && BUILD_VERB_RE.test(value) && PRODUCT_RE.test(value);
}
