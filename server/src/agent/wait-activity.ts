/**
 * Что панель показывает, пока запуск ждёт свободное место на сервере.
 *
 * Ожидание — это внутренняя механика платформы, а не состояние работы человека. Прежняя строка
 * «Сервер занят другим запуском — вы в очереди (впереди: 3)» заставляла закрывать вкладку, хотя
 * запуск шёл нормально и просто ждал освобождения места. Поэтому позиция в очереди не показывается
 * никогда: панель получает короткие нейтральные состояния подготовки, которые сменяют друг друга.
 *
 * Формулировки намеренно общие — это описание подготовки к работе, а не отчёт о сделанном: строки
 * не утверждают, что зависимость уже установлена или сборка прошла.
 *
 * Если места нет вовсе (очередь заполнена или ожидание истекло), запуск не начинается, и человек
 * видит единственное честное сообщение `PLATFORM_BUSY_MESSAGE` — без числа ожидающих и без слова
 * «очередь».
 */

export const WAIT_ACTIVITIES = [
  "Готовлю рабочее окружение…",
  "Проверяю зависимости проекта…",
  "Сверяюсь с файлами проекта…",
  "Собираю план изменений…",
] as const;

/** Код отказа «свободных мест нет». Отдельно от прежнего `SERVER_BUSY`, чтобы клиент сказал это своими словами. */
export const PLATFORM_BUSY_CODE = "PLATFORM_BUSY";

/**
 * Перегруженная платформа — это пауза, а не ошибка.
 *
 * Запуск не падает и не просит повторить: он сохраняется и продолжается сам, как только освободится
 * место. Человеку важно знать три вещи — что происходит, сколько это примерно займёт и что от него
 * ничего не требуется. Слово «ошибка» здесь неуместно: задача не потеряна.
 */
export const PLATFORM_PAUSED_MESSAGE =
  "Платформа сейчас перегружена — это займёт около 2 минут. Работа продолжится автоматически: запуск сохранён, это пауза, а не ошибка.";

/**
 * Повтор через минуту ожидания: обещание «около 2 минут» уже неверно, а молчать нельзя — человек
 * должен видеть, что пауза продолжается и всё ещё не требует его действий.
 */
export const PLATFORM_PAUSED_REMINDER =
  "Платформа всё ещё перегружена — жду свободное место. Работа продолжится автоматически, запуск сохранён.";

/** Сообщение на случай, когда запуск вообще не удалось поставить в ожидание. */
export const PLATFORM_BUSY_MESSAGE = "Платформа перегружена — повторите запуск через пару минут.";

/** Состояние ожидания по номеру тика: после последней строки снова первая. */
export function waitActivityAt(tick: number): string {
  const index = ((Math.trunc(tick) % WAIT_ACTIVITIES.length) + WAIT_ACTIVITIES.length) % WAIT_ACTIVITIES.length;
  return WAIT_ACTIVITIES[index]!;
}

export type WaitActivityEvent = { type: "run.activity"; activity: string };

/**
 * Шлёт `run.activity` сразу и затем по таймеру, пока не вызовут возвращённую функцию.
 *
 * Останавливать обязательно: строка подготовки не должна пережить сам запуск — иначе панель
 * останется с «готовлю окружение» на экране уже после того, как работа пошла.
 */
export function startWaitActivity(send: (event: WaitActivityEvent) => void, intervalMs: number): () => void {
  let tick = 0;
  const emit = () => send({ type: "run.activity", activity: waitActivityAt(tick++) });
  emit();
  const timer = setInterval(emit, Math.max(250, Math.trunc(intervalMs)));
  // Строка состояния не держит процесс: саму работу держит запуск, а не этот таймер.
  timer.unref?.();
  let stopped = false;
  return () => {
    if (stopped) return;
    stopped = true;
    clearInterval(timer);
  };
}
