/**
 * Что именно просят собрать.
 *
 * Заметка о мобильном проекте раньше стояла при любом запуске, если в проекте находилось
 * Expo-приложение, и требовала «первым действием вызови expo.build». В проекте, где корень —
 * веб-приложение, а мобильное лежит рядом (`admin-app`), это превращало любую просьбу «сделай
 * сборку» в запуск EAS: медленно и за кредиты пользователя.
 *
 * Поэтому заметка выбирается по реплике, а не только по устройству проекта:
 *
 * - `explicit` — назван признак мобильной сборки (android, ios, apk, aab, eas, expo, мобильное
 *   приложение) и есть глагол запуска: правило жёсткое, `expo.build` первым действием;
 * - `ambiguous` — просят «собрать приложение», но неизвестно, мобильное или веб: модель сначала
 *   выясняет это, а не запускает EAS наугад;
 * - `none` — сборку не просят (или просят только статус): `expo.build` не вызывается, но модель
 *   знает, где приложение, и не станет искать «способ залить архив» в REST, если сборку попросят
 *   следующим сообщением.
 */
export type MobileBuildIntent = "explicit" | "ambiguous" | "none";

/** Признаки именно мобильной сборки: их наличие снимает двусмысленность «приложения». */
const MOBILE_MARKER_RE =
  /(expo|\beas\b|android|андроид|\bios\b|айфон|\bapk\b|\baab\b|\bipa\b|мобильн|телефон|смартфон|google play|app store|плей ?маркет)/i;

/** Глагол запуска сборки: без него «android» в реплике — это правка или вопрос о статусе. */
const START_VERB_RE =
  /(собер|собра|пересобер|запуст|запуск|сделай|сделать|отправ|загру|выпуст|билд|\bbuild\b|\brelease\b)/i;

/** Вопрос о готовой сборке — это `expo.build_status`, а не новый запуск EAS. */
const STATUS_RE = /(статус|\bstatus\b|готов|прогресс|идёт|идет|проверь сборк|когда будет)/i;

/** «Приложение» без мобильного признака: может быть и веб-приложение проекта. */
const APP_WORD_RE = /(приложени|\bapp\b|апп)/i;

/**
 * Намерение по тексту последней реплики пользователя.
 */
export function mobileBuildIntent(text: string): MobileBuildIntent {
  const value = text ?? "";
  const starts = START_VERB_RE.test(value);
  if (STATUS_RE.test(value) && !starts) return "none";
  if (!starts) return "none";
  if (MOBILE_MARKER_RE.test(value)) return "explicit";
  if (APP_WORD_RE.test(value)) return "ambiguous";
  return "none";
}
