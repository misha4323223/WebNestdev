/**
 * Отказ прокси платформы — это не ошибка проекта.
 *
 * Контейнер, которому включили сеть (npm.install, pip.install, preview.start, EAS CLI), выходит
 * наружу только через прокси с allowlist. Когда домена нет в списке, прокси отвечает 403 текстом
 * «домен не входит в список разрешённых: <host>», и в логе установки это выглядит как обычная
 * ошибка пакетного менеджера. Агент в такой ситуации либо повторяет установку с другим флагом,
 * либо объясняет пользователю, что «в песочнице нет сети» — и то и другое неверно, потому что сеть
 * есть, а причина в списке доменов.
 *
 * Решение принимается по тексту, поэтому проверяется тестами без сети, без Docker и без прокси.
 */

/** Формулировки отказа из `describeEgressDeny` — единственный источник этих строк. */
const DENY_SIGN =
  /(не входит в список разрешённых|адреса метаданных облака запрещены|приватные адреса и внутренняя сеть платформы запрещены|разрешены только порты 80 и 443)/i;

export function isEgressDeny(text: string): boolean {
  return DENY_SIGN.test(text);
}

/** Имя домена из сообщения прокси: `... разрешённых: api.example.com`. */
export function deniedEgressHost(text: string): string | null {
  const match = text.match(/разрешённых:\s*([A-Za-z0-9.*_:-]{1,253})/)
    ?? text.match(/запрещены:\s*([A-Za-z0-9.*_:-]{1,253})/)
    // Отказ по порту формулируется иначе: «разрешены только порты 80 и 443: host:порт».
    ?? text.match(/только порты[^:]*:\s*([A-Za-z0-9.*_:-]{1,253})/);
  return match?.[1] ? match[1].toLowerCase().replace(/\.$/, "") : null;
}

/**
 * Готовая подсказка для результата инструмента. `undefined` — отказ не про фильтр, и тогда
 * подсказку не добавляем: иначе агент лечил бы настоящую ошибку проекта списком доменов.
 */
export function egressDenyHint(text: string): string | undefined {
  if (!isEgressDeny(text)) return undefined;
  const host = deniedEgressHost(text);
  return (
    "Прокси платформы не пустил " +
    (host ?? "домен") +
    ": это фильтр исходящей сети (EGRESS_MODE=allowlist), а не отсутствие сети у контейнера и не ошибка проекта. " +
    "Повтор той же команды с другими флагами не поможет. Реестр или адрес из конфигурации проекта должен быть разрешён " +
    "платформой; внешний API вызывается через net.request, файл скачивается через net.download."
  );
}
