#!/bin/sh
# Запуск контейнера сервера: API плюс, если включено, дверь публичных предпросмотров отдельным
# процессом (пункт 6.1 плана масштабирования).
#
# Зачем супервизор. Соединения открытых предпросмотров (вкладки и HMR-сокеты) держит именно дверь:
# пока она живёт в процессе API, шестьдесят предпросмотров добавляют память и файловые дескрипторы
# тому же процессу, что обслуживает панель. Отдельный процесс снимает это, но появляется вопрос
# жизненного цикла: упавшая дверь не должна ни ронять панель, ни требовать перезапуска контейнера,
# а упавший API не должен оставлять контейнер живым с одной дверью.
#
# Правила:
# - API — главный процесс: его выход завершает контейнер с его же кодом;
# - дверь перезапускается с паузой, а её штатный выход (код 0 — например, домена предпросмотра нет)
#   цикл заканчивает: перезапускать процесс, которому нечего делать, бессмысленно;
# - PREVIEW_DOOR_SEPARATE≠1 или отсутствие собранного door-main.js — поведение прежнее, один
#   процесс. Это же делает откат на предыдущий образ безопасным: старый образ этот файл не читает
#   вовсе, а новый без переменной поднимает дверь внутри API.
set -eu

if [ "${PREVIEW_DOOR_SEPARATE:-0}" != "1" ]; then
  exec "$@"
fi

door_script="server/dist/preview/door-main.js"
if [ ! -f "$door_script" ]; then
  echo "[supervisor] PREVIEW_DOOR_SEPARATE=1, но $door_script в образе нет — дверь остаётся в процессе API"
  export PREVIEW_DOOR_SEPARATE=0
  exec "$@"
fi

api_pid=""
door_pid=""

shutdown() {
  trap - TERM INT
  echo "[supervisor] остановка: передаю сигнал API и двери"
  [ -n "$door_pid" ] && kill -TERM "$door_pid" 2>/dev/null || true
  [ -n "$api_pid" ] && kill -TERM "$api_pid" 2>/dev/null || true
  # Дочерние процессы получают сигнал сами; ждём их, чтобы не оставить сирот в контейнере.
  wait 2>/dev/null || true
  exit 0
}
trap shutdown TERM INT

node server/dist/index.js &
api_pid=$!

(
  child=""
  # Сигнал доходит до подshell, а не до node: без этого перезапуск контейнера оставлял бы внутри
  # живой сиротский процесс двери, который продолжал бы держать порт 8788.
  trap 'trap - TERM INT; [ -n "$child" ] && kill -TERM "$child" 2>/dev/null; wait 2>/dev/null; exit 0' TERM INT
  while :; do
    node "$door_script" &
    child=$!
    code=0
    wait "$child" || code=$?
    if [ "$code" = "0" ]; then
      echo "[supervisor] дверь завершилась штатно (код 0) — больше не запускаю"
      break
    fi
    echo "[supervisor] дверь упала (код $code), перезапуск через 5 с"
    sleep 5
  done
) &
door_pid=$!

# Главный процесс — API. Его код возврата и есть код контейнера: выкатка и health-check должны
# видеть падение сервера, даже если дверь при этом жива.
# `wait` с ненулевым кодом под `set -e` завершил бы скрипт сразу, не остановив дверь: код
# сохраняется явно, чтобы порядок остановки оставался нашим.
api_code=0
wait "$api_pid" || api_code=$?
kill -TERM "$door_pid" 2>/dev/null || true
wait 2>/dev/null || true
exit "$api_code"
