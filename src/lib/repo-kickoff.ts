/**
 * Стартовый запрос после импорта репозитория.
 *
 * Раньше GitHub и GitLab просто открывали рабочую область, без задачи агенту: планировщик
 * появлялся пустым, и человек должен был сам догадаться написать запрос. Общий текст здесь
 * задаёт один порядок для всех коннекторов: сначала разобраться в проекте и его тарифе, потом
 * задать один вопрос, а не начинать установку или dev-сервер вслепую.
 */
export function importedRepositoryKickoff(input: {
  provider: string;
  fullName: string;
  defaultBranch: string;
}) {
  return `Импортирован репозиторий ${input.provider}: ${input.fullName} (ветка ${input.defaultBranch}).\n\n`
    + "Сначала, до любых изменений и запуска, изучи проект: определи стек, пакетный менеджер, скрипты установки/сборки/запуска, точки входа, "
    + "переменные окружения и наличие собственного backend, базы данных или постоянного сервера. Не запуская dev-сервер, реши, что это за проект и как он должен работать.\n\n"
    + "Обязательно сверь свои выводы с блоком PLAN FOR THIS RUN: если проекту нужен контейнерный/hybrid-предпросмотр или постоянный сервер, "
    + "а на текущем тарифе он недоступен, не пытайся обойти тариф и не запускай dev/start. Скажи об этом прямо и предложи перейти на «Премиум»; "
    + "на текущем тарифе предложи то, что действительно возможно: анализ проекта, статическую сборку или подготовку плана без запуска.\n\n"
    + "После анализа задай ровно один вопрос через question.ask: «Что сделать с проектом?» с вариантами «Глубокий анализ» "
    + "(разобрать стек, структуру, зависимости, риски и предложить улучшения, ничего не меняя) и «Запустить» "
    + "(установить зависимости, поднять предпросмотр и исправить только то, что мешает запуску). "
    + "Если запуск невозможен на текущем тарифе, в вопросе объясни это и не обещай запуск.\n\n"
    + "Если выбрали анализ — работай в режиме планировщика: изучи проект и собери через plan.update выводы и план улучшений. Файлы не меняй.\n\n"
    + "Если выбрали запуск — составь короткий план из трёх шагов: установить зависимости, запустить предпросмотр, проверить, что приложение открывается. "
    + "Ничего не меняй до перехода в режим разработчика: после него выполни этот план и покажи, что приложение работает.";
}
