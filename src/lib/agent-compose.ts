/**
 * Передача задачи агенту из другой панели.
 *
 * Панель «Тема» знает, что проекту нужна тема, но собрать её может только агент: это правка
 * файлов, а не запись токена. Событие вместо общего стора — самая короткая связь: панель
 * предпросмотра и панель агента живут в разных местах рабочей области и не делят состояние.
 * Если панели агента нет на экране, событие просто никто не услышит.
 */
export const AGENT_COMPOSE_EVENT = "webnestdev:compose";

export function composeAgentPrompt(prompt: string) {
  const text = prompt.trim();
  if (!text) return;
  window.dispatchEvent(new CustomEvent(AGENT_COMPOSE_EVENT, { detail: { prompt: text } }));
}

/**
 * Черновик в поле ввода агента — без отправки.
 *
 * Выбор элемента в предпросмотре знает, о каком элементе речь, но не знает, что с ним сделать:
 * «сделай крупнее» и «перекрась в акцент» — разные задачи. Поэтому в поле попадает описание
 * элемента, человек дописывает просьбу и отправляет сам.
 */
export const AGENT_DRAFT_EVENT = "webnestdev:compose-draft";

export function composeAgentDraft(draft: string) {
  const text = draft.trim();
  if (!text) return;
  window.dispatchEvent(new CustomEvent(AGENT_DRAFT_EVENT, { detail: { draft: text } }));
}

