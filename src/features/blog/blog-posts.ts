export const BLOG_PATH = "/blog";

export function blogPath(slug?: string): string {
  return slug ? BLOG_PATH + "/" + slug : BLOG_PATH;
}

/** Адрес статьи: `/blog/<slug>`, с косой чертой на конце или без неё. */
export function blogSlugFromPath(pathname: string): string | null {
  const match = /^\/blog\/([a-z0-9-]+)\/?$/.exec(pathname);
  return match ? match[1] : null;
}

export function isBlogPath(pathname: string): boolean {
  return pathname === BLOG_PATH || pathname === BLOG_PATH + "/" || blogSlugFromPath(pathname) !== null;
}

export function blogPost(slug: string): BlogPost | undefined {
  return BLOG_POSTS.find(post => post.slug === slug);
}
